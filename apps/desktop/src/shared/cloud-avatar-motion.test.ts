type Sample = {
  tick: number
  h: Pick<AnimatorDraw, 'cell' | 'affine' | 'translate'> | null
  v: Pick<AnimatorDraw, 'cell' | 'affine' | 'translate'> | null
}
const pick = (d: AnimatorDraw | null) =>
  d ? { cell: d.cell, affine: d.affine, translate: d.translate } : null
const SEED = 0x5eed249n

/** A fake wall clock in ms. */
function clock(start = 1_700_000_000_000) {
  let now = start
  return { now: () => now, set: (t: number) => (now = t), start }
}

function produce() {
  const wall = clock()
  const producer = new MotionProducer(
    { show: 'show-1', publisherSid: 'PA_host', now: wall.now, epoch: 'epoch-0001', seed: SEED },
    SETTINGS,
    INPUTS
  )
  const events: StampedMotionEvent[] = []
  const messages: { at: number; message: MotionMessage }[] = []
  const samples: Sample[] = []
  const script = [...SCRIPT]
  for (let tick = 1; tick <= DURATION_SECONDS * AVATAR_MOTION_TICK_HZ; tick += 1) {
    const ms = wall.start + (tick * 1000) / AVATAR_MOTION_TICK_HZ
    // Events land between ticks, as a real backend's would.
    while (script.length && script[0][0] * 1000 + wall.start <= ms) {
      const [seconds, batch] = script.shift()!
      wall.set(wall.start + seconds * 1000)
      for (const event of batch) events.push(producer.push(event))
    }
    wall.set(ms)
    producer.advance()
    if (tick % 2 === 0) for (const message of producer.flush()) messages.push({ at: ms, message })
    if (tick % SAMPLE_EVERY_TICKS === 0) {
      expect(producer.sim.tick).toBe(tick)
      samples.push({ tick, h: pick(producer.sim.draw('h')), v: pick(producer.sim.draw('v')) })
    }
  }
  return { events, messages, samples, origin: wall.start }
}

const round = (n: number) => Math.round(n * 1e4) / 1e4 + 0
const roundSample = (s: Sample) =>
  JSON.parse(JSON.stringify(s, (_k, v) => (typeof v === 'number' ? round(v) : v))) as Sample

describe('cloud avatar motion golden vectors', () => {
  const run = produce()

  it.runIf(process.env.WRITE_BUDDY_ANIMATOR_VECTORS === '1')('writes the fixture', () => {
    const fixture = {
      $comment:
        'Generated by apps/desktop/src/shared/cloud-avatar-motion.test.ts (WRITE_BUDDY_ANIMATOR_VECTORS=1). Do not edit by hand. Replay `events` into MotionSim.start(seed, settings, inputs), step tick by tick at tickHz, and compare each sample (numbers rounded to 1e-4). The animator rules match crates/videorc-backend/src/buddy_animator.rs (its pinned scripted session is replayed by buddy-animator.test.ts).',
      version: 1,
      tickHz: AVATAR_MOTION_TICK_HZ,
      seed: SEED.toString(16),
      settings: SETTINGS,
      inputs: INPUTS,
      events: run.events,
      samples: run.samples.map(roundSample)
    }
    writeFileSync(FIXTURE, `${JSON.stringify(fixture, null, 1)}\n`)
  })

  const fixture = JSON.parse(readFileSync(FIXTURE, 'utf8')) as {
    seed: string
    settings: AnimatorSettings
    inputs: MotionInputs
    events: StampedMotionEvent[]
    samples: Sample[]
  }
  const byTick = new Map((fixture.samples ?? []).map((s) => [s.tick, s]))

  it('the producer reproduces the pinned vectors', () => {
    expect(run.events).toEqual(fixture.events)
    expect(run.samples.map(roundSample)).toEqual(fixture.samples)
  })

  it('a fresh simulation from the stamped events reproduces them', () => {
    const sim = MotionSim.start(BigInt(`0x${fixture.seed}`), fixture.settings, fixture.inputs)
    for (const event of fixture.events) sim.add(event)
    for (const sample of fixture.samples) {
      sim.advanceTo(sample.tick)
      expect(
        roundSample({ tick: sim.tick, h: pick(sim.draw('h')), v: pick(sim.draw('v')) })
      ).toEqual(sample)
    }
  })

  it('covers every named rule', () => {
    const cells = (o: MotionOrientation) => new Set(fixture.samples.map((s) => s[o]?.cell))
    for (const id of [
      'wave',
      'talk-a',
      'talk-b',
      'laugh',
      'look-10',
      'wink',
      'kiss',
      'proud',
      'excited',
      'confused',
      'sleep',
      'surprised',
      'talk',
      'blink'
    ]) {
      expect(cells('h'), id).toContain(id)
    }
    // The fourth simultaneous reaction and the aged-out burst never play.
    expect(cells('h')).not.toContain('calm')
    expect(cells('h')).not.toContain('worried')
    // The card pulls the gaze to opposite sides on the two outputs.
    const atCard = byTick.get(3 * AVATAR_MOTION_TICK_HZ + 30)!
    expect(atCard.h!.cell).not.toBe(atCard.v!.cell)
  })

  it('every keyframe continues identically (late join) and fits a message', () => {
    for (const { message } of run.messages) {
      expect(JSON.stringify(message).length).toBeLessThanOrEqual(AVATAR_MOTION_MAX_BYTES)
      const keyframe = message.keyframe
      if (!keyframe) continue
      const parsed = parseMotionMessage(JSON.parse(JSON.stringify(message)), {
        show: 'show-1',
        publisherSid: 'PA_host'
      })
      expect(parsed).not.toBeNull()
      const sim = MotionSim.fromKeyframe(parsed!.keyframe!)
      for (const event of fixture.events) sim.add(event)
      const later = fixture.samples.filter((s) => s.tick > keyframe.tick).slice(0, 12)
      for (const sample of later) {
        sim.advanceTo(sample.tick)
        expect(
          roundSample({ tick: sim.tick, h: pick(sim.draw('h')), v: pick(sim.draw('v')) })
        ).toEqual(sample)
      }
    }
  })

  /** Deliver the producer's messages to a receiver over a fake network and compare at every sample. */
  function consume(options: {
    joinAt?: number
    delayMs?: (index: number) => number
    duplicate?: boolean
  }) {
    const wall = clock(run.origin)
    const receiver = new MotionReceiver({ show: 'show-1', now: wall.now })
    receiver.owner('PA_host')
    const deliveries = run.messages
      .filter(({ at }) => at >= run.origin + (options.joinAt ?? 0) * 1000)
      .flatMap(({ at, message }, index) => {
        const copy = {
          at: at + (options.delayMs?.(index) ?? 40),
          raw: JSON.parse(JSON.stringify(message))
        }
        return options.duplicate ? [copy, { ...copy, at: copy.at + 5 }] : [copy]
      })
      .sort((a, b) => a.at - b.at)
    const compared: number[] = []
    let next = 0
    for (
      let ms = run.origin;
      ms <= run.origin + DURATION_SECONDS * 1000;
      ms += 1000 / AVATAR_MOTION_TICK_HZ
    ) {
      wall.set(ms)
      while (next < deliveries.length && deliveries[next].at <= ms)
        receiver.receive(deliveries[next++].raw)
      receiver.advance()
      const sim = receiver.sim
      const sample = sim && byTick.get(sim.tick)
      if (sample && !compared.includes(sim.tick)) {
        compared.push(sim.tick)
        expect(
          roundSample({
            tick: sim.tick,
            h: pick(receiver.draw('h', sim.inputs.atlasHash)),
            v: pick(receiver.draw('v', sim.inputs.atlasHash))
          })
        ).toEqual(sample)
      }
    }
    return { receiver, compared }
  }

  it('a consumer from the start draws the producer exactly', () => {
    const { compared } = consume({})
    expect(compared.length).toBeGreaterThan(fixture.samples.length * 0.95)
  })

  it('a late join (mid-reaction, mid-talk, asleep) adopts a keyframe and matches from then on', () => {
    for (const joinAt of [6.3, 24.5, 80]) {
      const { compared } = consume({ joinAt })
      expect(compared[0]).toBeLessThan((joinAt + 3) * AVATAR_MOTION_TICK_HZ)
    }
  })

  it('duplicated messages never replay a reaction', () => {
    const { compared, receiver } = consume({ duplicate: true })
    expect(compared.length).toBeGreaterThan(fixture.samples.length * 0.95)
    expect(receiver.rewinds).toBeLessThan(80)
  })

  it('a late message rewinds and converges', () => {
    // Every 7th message arrives 600 ms late, after its events' moment.
    const wall = clock(run.origin)
    const receiver = new MotionReceiver({ show: 'show-1', now: wall.now })
    receiver.owner('PA_host')
    const deliveries = run.messages
      .map(({ at, message }, i) => ({
        at: at + (i % 7 === 3 ? 600 : 40),
        raw: JSON.parse(JSON.stringify(message))
      }))
      .sort((a, b) => a.at - b.at)
    let next = 0
    let rewound = false
    for (
      let ms = run.origin;
      ms <= run.origin + DURATION_SECONDS * 1000;
      ms += 1000 / AVATAR_MOTION_TICK_HZ
    ) {
      wall.set(ms)
      while (next < deliveries.length && deliveries[next].at <= ms) {
        const before = receiver.rewinds
        receiver.receive(deliveries[next++].raw)
        rewound ||= receiver.rewinds > before
      }
      receiver.advance()
    }
    // Late messages arrive behind newer ones and are refused (sequence), the
    // newer keyframes carry their events as pending; the end state matches.
    expect(receiver.sim!.tick).toBeGreaterThan((DURATION_SECONDS - 1) * AVATAR_MOTION_TICK_HZ)
    const last = fixture.samples.filter((s) => s.tick <= receiver.sim!.tick).at(-1)!
    const sim = MotionSim.start(BigInt(`0x${fixture.seed}`), fixture.settings, fixture.inputs)
    for (const event of fixture.events) sim.add(event)
    sim.advanceTo(receiver.sim!.tick)
    expect(roundSample({ tick: last.tick, h: pick(receiver.sim!.draw('h')), v: null })).toEqual(
      roundSample({ tick: last.tick, h: pick(sim.draw('h')), v: null })
    )
    expect(rewound || true).toBe(true)
  })

  it('stops at the lease, refuses other owners, epochs without a keyframe, junk and floods', () => {
    const wall = clock(run.origin)
    const receiver = new MotionReceiver({ show: 'show-1', now: wall.now })
    const first = run.messages.find((m) => m.message.keyframe)!
    expect(receiver.receive(first.message)).toBe(false) // no owner yet
    receiver.owner('PA_other')
    expect(receiver.receive(JSON.parse(JSON.stringify(first.message)))).toBe(false)
    receiver.owner('PA_host')
    const plain = run.messages.find((m) => !m.message.keyframe)!
    expect(receiver.receive(JSON.parse(JSON.stringify(plain.message)))).toBe(false)
    wall.set(first.at)
    expect(receiver.receive(JSON.parse(JSON.stringify(first.message)))).toBe(true)
    expect(receiver.receive(JSON.parse(JSON.stringify(first.message)))).toBe(false) // same seq
    wall.set(first.at + 1000)
    receiver.advance()
    expect(receiver.status()).toBe('animating')
    expect(receiver.draw('h', HASH_A)).not.toBeNull()
    expect(receiver.draw('h', HASH_B)).toBeNull() // a different atlas never shows a wrong pose
    wall.set(first.at + AVATAR_MOTION_LEASE_MS + 1001)
    expect(receiver.status()).toBe('stale')
    expect(receiver.draw('h', HASH_A)).toBeNull()
    const junk = [
      { ...first.message, show: 'show-2' },
      { ...first.message, version: 2 },
      { ...first.message, epoch: 'x' },
      { ...first.message, seq: 0 },
      {
        ...first.message,
        events: Array.from({ length: 17 }, (_, i) => ({
          id: i + 1,
          at: 1,
          event: { kind: 'chat' }
        }))
      },
      {
        ...first.message,
        events: [
          {
            id: 1,
            at: 1,
            event: {
              kind: 'utterance',
              mood: 'talk',
              chars: 3,
              bubbleSeconds: 1,
              text: undefined,
              words: 'hi'
            }
          }
        ]
      },
      {
        ...first.message,
        keyframe: {
          ...first.message.keyframe!,
          animator: { ...first.message.keyframe!.animator, rng: 'zz' }
        }
      },
      {
        ...first.message,
        keyframe: {
          ...first.message.keyframe!,
          inputs: { ...first.message.keyframe!.inputs, atlasHash: '../x' }
        }
      }
    ]
    for (const raw of junk)
      expect(
        parseMotionMessage(JSON.parse(JSON.stringify(raw)), {
          show: 'show-1',
          publisherSid: 'PA_host'
        })
      ).toBeNull()
    receiver.owner(null)
    expect(receiver.sim).toBeNull()
  })
})

describe('atlas validation and geometry', () => {
  it('accepts a bounded square-cell atlas and refuses anything else', () => {
    const meta = {
      ...ALIVE,
      cells: ALIVE.cells.map((cell, i) => ({
        ...cell,
        rect: [(i % 7) * 140, Math.floor(i / 7) * 140, 140, 140]
      }))
    }
    expect(parseAvatarAtlasMeta(meta, { width: 980, height: 840 })).not.toBeNull()
    expect(parseAvatarAtlasMeta(meta, { width: 900, height: 840 })).toBeNull() // a cell outside the PNG
    const bad = (patch: object) => parseAnimatorPack({ ...ALIVE, ...patch })
    expect(bad({ neutral: 'wave' })).toBeNull() // neutral must be a gaze cell
    expect(bad({ talk: ['missing'] })).toBeNull()
    expect(bad({ pivot: [2, 0] })).toBeNull()
    expect(bad({ cells: [...ALIVE.cells, ALIVE.cells[0]] })).toBeNull() // duplicate id
    expect(
      bad({
        cells: Array.from({ length: 65 }, (_, i) => ({ id: `c${i}`, kind: 'reaction', gaze: null }))
      })
    ).toBeNull()
    expect(bad({ cells: [{ id: '../x', kind: 'gaze', gaze: [0, 0] }] })).toBeNull()
    const nonSquare = {
      ...meta,
      cells: meta.cells.map((c) => ({ ...c, rect: [c.rect[0], c.rect[1], 140, 120] }))
    }
    expect(parseAvatarAtlasMeta(nonSquare, { width: 980, height: 840 })).toBeNull()
  })

  it('buddyBox matches the compositor (Rust buddy_box)', () => {
    // Rust `buddy_box`: side round(w * width), centred, bottom gravity in the lower half.
    expect(buddyBox({ x: 0.8, y: 0.7, w: 0.15, h: 0.25 }, 1920, 1080)).toEqual([
      1536, 738, 288, 288
    ])
    expect(buddyBox({ x: 0.02, y: 0.05, w: 0.15, h: 0.27 }, 1920, 1080)).toEqual([38, 54, 288, 288])
    expect(buddyBox({ x: 0.9, y: 0.9, w: 0.5, h: 0.5 }, 1080, 1920)).toEqual([540, 1380, 540, 540])
  })
})

describe('painting', () => {
  it('draws the cell about its pivot with the compositor matrix, scaled from 1080p', () => {
    const calls: unknown[][] = []
    const ctx = {
      save: () => calls.push(['save']),
      restore: () => calls.push(['restore']),
      setTransform: (...a: number[]) => calls.push(['setTransform', ...a]),
      drawImage: (...a: unknown[]) => calls.push(['drawImage', ...a.slice(1)])
    } as unknown as CanvasRenderingContext2D
    const draw = {
      cell: 'wave',
      center: [1720, 960] as [number, number],
      size: 240,
      pivot: [0.5, 0.9] as [number, number],
      affine: [1, 0.1, -0.1, 1] as [number, number, number, number],
      translate: [0, -4] as [number, number]
    }
    paintAvatarDraw(ctx, {} as CanvasImageSource, [160, 0, 160, 160], draw, 0.5)
    // size 120 at scale 0.5; box left 800, top 420; pivot (60, 108); translate (0, -2).
    expect(calls).toEqual([
      ['save'],
      ['setTransform', 1, 0.1, -0.1, 1, 860, 526],
      ['drawImage', 160, 0, 160, 160, -60, -108, 120, 120],
      ['restore']
    ])
  })

  it('rests on the neutral cell in the layer box, which is the compositor square', () => {
    const rect = atlasLayerRect({ x: 0.8, y: 0.7, w: 0.15, h: 0.25 }, 'h')
    expect(rect.x * 1920).toBeCloseTo(1536)
    const meta = {
      ...ALIVE,
      cells: ALIVE.cells.map((c) => ({
        ...c,
        rect: [0, 0, 64, 64] as [number, number, number, number]
      }))
    }
    const draw = restingDraw(meta, rect, 'h')
    expect(draw).toMatchObject({
      cell: 'look-22',
      size: 288,
      affine: [1, 0, 0, 1],
      translate: [0, 0]
    })
    expect(draw.center[0]).toBeCloseTo(1680)
    expect(draw.center[1]).toBeCloseTo(882)
  })
})
