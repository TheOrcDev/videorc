const GAZE = [-1, -0.5, 0, 0.5, 1]
function pack(grid: boolean, reactions: string[], talk: string[]): AnimatorPack {
  const cells: AnimatorPack['cells'][number][] = []
  for (const y of GAZE)
    for (const x of GAZE) {
      if (grid || (x === 0 && y === 0))
        cells.push({ id: `look-${GAZE.indexOf(x)}${GAZE.indexOf(y)}`, kind: 'gaze', gaze: [x, y] })
    }
  for (const id of reactions) cells.push({ id, kind: 'reaction', gaze: null })
  return { neutral: 'look-22', pivot: [0.5, 0.9], headTop: 0.2, talk, cells }
}
