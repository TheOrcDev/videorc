// Lists the tests a Rust binary crate declares, from its sources alone, for
// one target's cfg. A required-test list checked against this breaks a fast
// Node test when a module moves or a cfg gate changes, instead of a cargo
// `--list` run that only exists after a full target build (issue #1073).
//
// It handles the patterns videorc-backend uses, not all of Rust:
// - `mod name;` resolves to `name.rs` or `name/mod.rs` beside a mod-rs file
//   (main.rs, mod.rs, a `#[path]` file), or under `file/` beside `file.rs`;
//   `#[path = "..."]` is relative to the declaring file's directory;
// - inline `mod name { ... }`, outer `#[cfg(...)]` on mods and fns, and an
//   inner `#![cfg(...)]` at the top of a file;
// - a test is a free fn in a module carrying `#[test]` or `#[<path>::test]`
//   (`#[tokio::test]`, `#[tokio::test(...)]`).
// Tests generated by macros are invisible to it. An unknown cfg predicate or
// a `#[path]` inside an inline module throws rather than guessing.

import { existsSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** `cargo test` on 64-bit Windows with the crate's default (empty) features. */
export const WINDOWS_TEST_CFG = Object.freeze({
  target_os: 'windows',
  target_family: 'windows',
  target_pointer_width: '64',
  flags: Object.freeze(['windows', 'test', 'debug_assertions']),
  features: Object.freeze([])
})

/**
 * Every `#[test]` fn reachable from `rootFile`, as
 * `{ name, enabled, file }`: `name` is the path `cargo test -- --list`
 * prints, `enabled` whether every enclosing cfg holds under `cfg`.
 */
export function listRustSourceTests(rootFile, cfg = WINDOWS_TEST_CFG) {
  const tests = []
  walkModuleFile(rootFile, { modulePath: [], modRs: true, enabled: true, cfg, tests })
  return tests
}

function walkModuleFile(file, { modulePath, modRs, enabled, cfg, tests }) {
  const tokens = tokenizeRust(readFileSync(file, 'utf8'))
  const fileDir = dirname(file)
  const stem = file.slice(fileDir.length + 1).replace(/\.rs$/, '')
  const childDir = modRs ? fileDir : join(fileDir, stem)
  let index = 0
  // Inner attributes lead the file; only `#![cfg]` changes what compiles.
  while (tokens[index] === '#' && tokens[index + 1] === '!' && tokens[index + 2] === '[') {
    const end = matchingClose(tokens, index + 2)
    const attribute = tokens.slice(index + 3, end)
    if (attribute[0] === 'cfg') enabled &&= evaluateCfg(attribute.slice(1), cfg)
    index = end + 1
  }
  // Scope stack: a module scope can declare tests; any other block cannot.
  const scopes = [{ module: true, modulePath, childDir, enabled, inline: false }]
  let attributes = []
  for (; index < tokens.length; index += 1) {
    const token = tokens[index]
    const scope = scopes.at(-1)
    if (token === '#' && tokens[index + 1] === '[') {
      const end = matchingClose(tokens, index + 1)
      attributes.push(tokens.slice(index + 2, end))
      index = end
      continue
    }
    if (token === 'mod' && isIdentifier(tokens[index + 1]) && scope.module) {
      const name = tokens[index + 1]
      const next = tokens[index + 2]
      const childEnabled = scope.enabled && attributesEnabled(attributes, cfg)
      const pathAttribute = attributes.find((attribute) => attribute[0] === 'path')
      attributes = []
      if (next === ';') {
        let childFile
        let childModRs
        if (pathAttribute) {
          if (scope.inline) {
            throw new Error(`#[path] inside an inline module is not supported (${file})`)
          }
          childFile = join(fileDir, rustStringValue(pathAttribute.at(-1)))
          childModRs = true
        } else {
          const nonModRs = join(scope.childDir, `${name}.rs`)
          const modRsFile = join(scope.childDir, name, 'mod.rs')
          childModRs = !existsSync(nonModRs)
          childFile = childModRs ? modRsFile : nonModRs
          if (!existsSync(childFile)) throw new Error(`mod ${name} in ${file} has no source file`)
        }
        walkModuleFile(childFile, {
          modulePath: [...scope.modulePath, name],
          modRs: childModRs,
          enabled: childEnabled,
          cfg,
          tests
        })
        index += 2
        continue
      }
      if (next === '{') {
        scopes.push({
          module: true,
          modulePath: [...scope.modulePath, name],
          childDir: join(scope.childDir, name),
          enabled: childEnabled,
          inline: true
        })
        index += 2
        continue
      }
    }
    if (token === 'fn' && isIdentifier(tokens[index + 1]) && scope.module) {
      if (attributes.some(isTestAttribute)) {
        tests.push({
          name: [...scope.modulePath, tokens[index + 1]].join('::'),
          enabled: scope.enabled && attributesEnabled(attributes, cfg),
          file
        })
      }
      attributes = []
      continue
    }
    if (token === '{') {
      scopes.push({ module: false })
      attributes = []
    } else if (token === '}') {
      scopes.pop()
      attributes = []
    } else if (token === ';') {
      attributes = []
    }
  }
}

function isIdentifier(token) {
  return typeof token === 'string' && /^[A-Za-z_][A-Za-z0-9_]*$/.test(token)
}

function isTestAttribute(attribute) {
  if (attribute.length === 1) return attribute[0] === 'test'
  // `tokio::test` or `tokio::test(flavor = ...)`
  return attribute[1] === ':' && attribute[2] === ':' && attribute[3] === 'test'
}

function attributesEnabled(attributes, cfg) {
  return attributes
    .filter((attribute) => attribute[0] === 'cfg')
    .every((attribute) => evaluateCfg(attribute.slice(1), cfg))
}

/** `tokens` is the parenthesised predicate, `( ... )`, of one `cfg`. */
export function evaluateCfg(tokens, cfg = WINDOWS_TEST_CFG) {
  if (tokens[0] !== '(' || tokens.at(-1) !== ')') {
    throw new Error(`Malformed cfg: ${tokens.join(' ')}`)
  }
  const [value, end] = evaluatePredicate(tokens, 1, cfg)
  if (end !== tokens.length - 1) throw new Error(`Malformed cfg: ${tokens.join(' ')}`)
  return value
}

function evaluatePredicate(tokens, index, cfg) {
  const head = tokens[index]
  if (head === 'all' || head === 'any' || head === 'not') {
    if (tokens[index + 1] !== '(') throw new Error(`Malformed cfg ${head}: ${tokens.join(' ')}`)
    const values = []
    let cursor = index + 2
    while (tokens[cursor] !== ')') {
      const [value, next] = evaluatePredicate(tokens, cursor, cfg)
      values.push(value)
      cursor = tokens[next] === ',' ? next + 1 : next
    }
    if (head === 'not' && values.length !== 1) throw new Error('cfg not() takes one predicate')
    const value =
      head === 'all' ? values.every(Boolean) : head === 'any' ? values.some(Boolean) : !values[0]
    return [value, cursor + 1]
  }
  if (!isIdentifier(head)) throw new Error(`Unknown cfg predicate: ${tokens.join(' ')}`)
  if (tokens[index + 1] === '=') {
    const expected = rustStringValue(tokens[index + 2])
    if (head === 'feature') return [cfg.features.includes(expected), index + 3]
    if (!Object.hasOwn(cfg, head)) throw new Error(`Unknown cfg key: ${head}`)
    return [cfg[head] === expected, index + 3]
  }
  if (cfg.flags.includes(head)) return [true, index + 1]
  if (['unix', 'test', 'debug_assertions', 'windows', 'miri'].includes(head)) {
    return [false, index + 1]
  }
  throw new Error(`Unknown cfg flag: ${head}`)
}

function rustStringValue(token) {
  if (typeof token !== 'string' || !token.startsWith('"')) {
    throw new Error(`Expected a string literal, got ${token}`)
  }
  return JSON.parse(token)
}

function matchingClose(tokens, openIndex) {
  const open = tokens[openIndex]
  const close = { '(': ')', '[': ']', '{': '}' }[open]
  let depth = 0
  for (let index = openIndex; index < tokens.length; index += 1) {
    if (tokens[index] === open) depth += 1
    else if (tokens[index] === close && --depth === 0) return index
  }
  throw new Error(`Unclosed ${open}`)
}

/**
 * Splits Rust source into identifiers, punctuation and plain string
 * literals; comments, raw/byte strings, char literals and lifetimes are
 * dropped so their braces never unbalance a scope.
 */
export function tokenizeRust(source) {
  const tokens = []
  const length = source.length
  let index = 0
  while (index < length) {
    const char = source[index]
    const next = source[index + 1]
    if (/\s/.test(char)) {
      index += 1
    } else if (char === '/' && next === '/') {
      const end = source.indexOf('\n', index)
      index = end < 0 ? length : end + 1
    } else if (char === '/' && next === '*') {
      let depth = 1
      index += 2
      while (index < length && depth > 0) {
        if (source[index] === '/' && source[index + 1] === '*') {
          depth += 1
          index += 2
        } else if (source[index] === '*' && source[index + 1] === '/') {
          depth -= 1
          index += 2
        } else {
          index += 1
        }
      }
    } else if (
      (char === 'r' || (char === 'b' && next === 'r')) &&
      /^b?r#*"/.test(source.slice(index, index + 260))
    ) {
      const [opening, hashes] = /^b?r(#*)"/.exec(source.slice(index, index + 260))
      const closing = `"${hashes}`
      const end = source.indexOf(closing, index + opening.length)
      if (end < 0) throw new Error('Unclosed raw string')
      index = end + closing.length
    } else if (char === '"' || ((char === 'b' || char === 'c') && next === '"')) {
      const start = char === '"' ? index : index + 1
      let cursor = start + 1
      while (cursor < length && source[cursor] !== '"') {
        cursor += source[cursor] === '\\' ? 2 : 1
      }
      if (start === index) tokens.push(source.slice(start, cursor + 1))
      index = cursor + 1
    } else if (char === "'" || (char === 'b' && next === "'")) {
      const start = char === "'" ? index : index + 1
      const width = source.codePointAt(start + 1) > 0xffff ? 2 : 1
      if (source[start + 1] === '\\') {
        // `'\n'`, `'\''`, `'\u{..}'`: the closing quote follows the escape
        index = source.indexOf("'", start + 3) + 1
      } else if (source[start + 1 + width] === "'") {
        index = start + 2 + width
      } else {
        // a lifetime or label: skip the quote, the identifier follows
        index = start + 1
      }
    } else if (/[A-Za-z_]/.test(char)) {
      let cursor = index + 1
      while (cursor < length && /[A-Za-z0-9_]/.test(source[cursor])) cursor += 1
      tokens.push(source.slice(index, cursor))
      index = cursor
    } else if (/[0-9]/.test(char)) {
      let cursor = index + 1
      while (cursor < length && /[A-Za-z0-9_.]/.test(source[cursor])) {
        if (source[cursor] === '.' && !/[0-9]/.test(source[cursor + 1] ?? '')) break
        cursor += 1
      }
      index = cursor
    } else {
      tokens.push(char)
      index += 1
    }
  }
  return tokens
}
