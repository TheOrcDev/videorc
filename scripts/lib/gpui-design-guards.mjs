// Plan 260 S2.2d: the videorc-design skill's guards for the GPUI app, the
// Rust twins of apps/desktop/src/renderer/src/renderer-style-guards.test.ts
// and renderer-shortcut-guard.test.ts. They read the Rust sources of the
// screens (apps/videorc/src) and of the synced kit (crates/videorc-kit/src)
// and fail on:
//
// - a raw colour: every colour is a token from the generated tokens.rs;
// - a radius off the tiers: panel, row, tag, chip and full, and popup (LG)
//   only on the floating surfaces;
// - text below 11 px;
// - a hand-typed shortcut (a key glyph or "Cmd+"): ShortcutKeys prints
//   shortcuts from the keymap, per platform;
// - a tinted toast: a toast's type colours its icon only.
//
// Comments never count, and neither does a `#[cfg(test)] mod`, where tests
// plant the very things these guards forbid.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

/** The roots the guards read, relative to the repository. */
export const GPUI_ROOTS = ['apps/videorc/src', 'crates/videorc-kit/src']

/** Generated by videorc-ui's `pnpm theme:build`; it is where colours, radii and sizes live. */
export const TOKENS_FILE = 'crates/videorc-kit/src/tokens.rs'

/**
 * Splits Rust source into code and the text of its literals. `code` keeps
 * every offset and newline, with comments and the insides of string and
 * char literals blanked to spaces; `strings` holds each literal's text
 * (with `\u{…}` escapes decoded) and its line.
 */
export function lexRust(source) {
  const out = [...source]
  const strings = []
  let line = 1
  const blank = (from, to) => {
    for (let index = from; index < to; index += 1) {
      if (out[index] !== '\n') out[index] = ' '
    }
  }
  const linesIn = (from, to) => {
    let count = 0
    for (let index = from; index < to; index += 1) if (source[index] === '\n') count += 1
    return count
  }
  const literal = (open, close, textFrom, textTo) => {
    const raw = source.slice(textFrom, textTo)
    strings.push({
      at: open,
      line,
      text: raw.replace(/\\u\{([0-9a-fA-F]{1,6})\}/g, (_, hex) =>
        String.fromCodePoint(Number.parseInt(hex, 16))
      )
    })
    blank(textFrom, textTo)
    line += linesIn(open, close)
  }
  let index = 0
  while (index < source.length) {
    const char = source[index]
    const next = source[index + 1]
    if (char === '\n') {
      line += 1
      index += 1
    } else if (char === '/' && next === '/') {
      const end = source.indexOf('\n', index)
      const stop = end === -1 ? source.length : end
      blank(index, stop)
      index = stop
    } else if (char === '/' && next === '*') {
      let depth = 1
      let cursor = index + 2
      while (cursor < source.length && depth > 0) {
        if (source.startsWith('/*', cursor)) {
          depth += 1
          cursor += 2
        } else if (source.startsWith('*/', cursor)) {
          depth -= 1
          cursor += 2
        } else {
          cursor += 1
        }
      }
      blank(index, cursor)
      line += linesIn(index, cursor)
      index = cursor
    } else if (
      /[rbc]/.test(char) &&
      !/[\w]/.test(source[index - 1] ?? '') &&
      /^(?:br|cr|r)#*"/.test(source.slice(index, index + 260))
    ) {
      // A raw string: r"…", r#"…"#, br"…", cr"…".
      const [, hashes] = /^(?:br|cr|r)(#*)"/.exec(source.slice(index))
      const textFrom = index + source.slice(index).indexOf('"') + 1
      const closing = `"${hashes}`
      const end = source.indexOf(closing, textFrom)
      const textTo = end === -1 ? source.length : end
      literal(index, textTo, textFrom, textTo)
      index = textTo + closing.length
    } else if (char === '"') {
      let cursor = index + 1
      while (cursor < source.length && source[cursor] !== '"') {
        cursor += source[cursor] === '\\' ? 2 : 1
      }
      literal(index, cursor, index + 1, cursor)
      index = cursor + 1
    } else if (char === "'") {
      // A char literal ('x', '\n', '\u{2318}'), or a lifetime or label ('a).
      const escaped = /^'\\(?:u\{[0-9a-fA-F]{1,6}\}|x[0-9a-fA-F]{2}|.)'/.exec(source.slice(index))
      const plain = /^'([^\\'\n])'/u.exec(source.slice(index))
      const match = escaped ?? plain
      if (match) {
        const end = index + match[0].length - 1
        literal(index, end, index + 1, end)
        index = end + 1
      } else {
        index += 1
      }
    } else {
      index += 1
    }
  }
  const { code, tests } = blankTestModules(out.join(''))
  return {
    code,
    strings: strings
      .filter(({ at }) => !tests.some(([from, to]) => at >= from && at < to))
      .map(({ line, text }) => ({ line, text }))
  }
}

/**
 * Blanks each `#[cfg(test)] mod name { … }` (tests plant what the guards
 * forbid) and returns their ranges, so their literals are dropped too.
 */
function blankTestModules(code) {
  const out = [...code]
  const tests = []
  const pattern = /#\[cfg\(test\)\]\s*mod\s+\w+\s*\{/g
  for (const match of code.matchAll(pattern)) {
    let depth = 1
    let cursor = match.index + match[0].length
    while (cursor < code.length && depth > 0) {
      if (code[cursor] === '{') depth += 1
      if (code[cursor] === '}') depth -= 1
      cursor += 1
    }
    tests.push([match.index, cursor])
    for (let index = match.index; index < cursor; index += 1) {
      if (out[index] !== '\n') out[index] = ' '
    }
  }
  return { code: out.join(''), tests }
}

const lineOf = (code, index) => code.slice(0, index).split('\n').length

function codeOffenders(path, code, pattern, why) {
  const found = []
  for (const match of code.matchAll(
    new RegExp(pattern.source, `${pattern.flags.replace('g', '')}g`)
  )) {
    found.push(`${path}:${lineOf(code, match.index)}: ${why(match)}`)
  }
  return found
}

// ---------------------------------------------------------------- colours

const RAW_COLOUR_CALLS = [
  // gpui::rgb(0x…), gpui::rgba(0x…): a token is `rgba(theme.x)` or `hsla(theme.x)`.
  /\brgba?\s*\(\s*0x[0-9a-fA-F]+/,
  // gpui::hsla(h, s, l, a) with numbers.
  /\bhsla\s*\(\s*-?[\d.]/,
  // A colour built field by field (not `-> Hsla {`, a function's body).
  /\b(?:Hsla|Rgba)\s*\{\s*[hslargb]\s*:/,
  // GPUI's named colours; transparent_black() and transparent_white() are no colour.
  /\b(?:Hsla::|gpui::)?(?:black|white|red|green|blue|yellow)\s*\(\s*\)/,
  // A colour constant: a six- or eight-digit hex literal.
  /\b0x(?:[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b/
]
const HEX_STRING = /^#(?:[0-9a-fA-F]{3,4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/
const SVG_HEX = /\b(?:fill|stroke|stop-color|color)\s*=\s*["']?#[0-9a-fA-F]{3,8}\b/

/**
 * Files whose colour literals are not theme colours, each with its reason.
 * tokens.rs is skipped as a whole (it is where the colours live).
 */
export const COLOUR_LITERAL_ALLOWLIST = new Map([
  [
    'crates/videorc-kit/src/chrome.rs',
    "the chromatic ring's mask channels (MASK_WHITE, MASK_BLACK): a sprite's opacity is its mask, tinted to light or shade"
  ],
  [
    'crates/videorc-kit/src/qr_code.rs',
    'QR codes stay black on white for scanners in both themes (Electron Phone Pair / watchdog)'
  ]
])

/** Colours that are not tokens: a raw colour call, constant, or hex string. */
export function rawColourOffenders(path, { code, strings }) {
  if (COLOUR_LITERAL_ALLOWLIST.has(path)) return []
  const found = RAW_COLOUR_CALLS.flatMap((pattern) =>
    codeOffenders(path, code, pattern, (match) => match[0].trim())
  )
  for (const { line, text } of strings) {
    if (HEX_STRING.test(text.trim()) || SVG_HEX.test(text)) {
      found.push(`${path}:${line}: ${JSON.stringify(text.slice(0, 60))}`)
    }
  }
  return onePerLine(found)
}

// ---------------------------------------------------------------- radii

/** GPUI's Tailwind radius scale and literal radii: neither is a tier. */
const OFF_TIER_RADIUS = [
  /\.rounded(?:_(?:t|b|l|r|tl|tr|bl|br))?_(?:xs|sm|md|lg|xl|2xl|3xl)\s*\(/,
  /\.rounded(?:_(?:t|b|l|r|tl|tr|bl|br))?\s*\(\s*(?:px|rems?)\s*\(\s*[\d.]/,
  // The stylesheet's size scale, kept in tokens.rs for the React flavour.
  /\bradius::(?:SM|MD|XL)\b/
]
/** The popup tier (10 px): menus, selects, popovers, hover cards, tooltips. */
const POPUP_RADIUS = /\bradius::LG\b/
export const POPUP_TIER_FILES = new Set(
  ['dropdown_menu', 'context_menu', 'select', 'popover', 'hover_card', 'tooltip', 'chart'].map(
    (name) => `crates/videorc-kit/src/${name}.rs`
  )
)

/** Radii off the tiers: panel, row, tag, chip, full; popup only on floating surfaces. */
export function offTierRadiusOffenders(path, { code }) {
  const found = OFF_TIER_RADIUS.flatMap((pattern) =>
    codeOffenders(path, code, pattern, (match) => match[0].trim())
  )
  if (!POPUP_TIER_FILES.has(path)) {
    found.push(
      ...codeOffenders(path, code, POPUP_RADIUS, () => 'radius::LG off a floating surface')
    )
  }
  return found.sort(byLine)
}

// ---------------------------------------------------------------- text

const SMALLEST_TEXT_PX = 11
const TEXT_SIZES = [
  { pattern: /\b(?:text_size|font_size)\s*\(\s*px\s*\(\s*([\d.]+)/, px: (value) => value },
  { pattern: /\b(?:text_size|font_size)\s*\(\s*rems?\s*\(\s*([\d.]+)/, px: (value) => value * 16 },
  { pattern: /\bsize\s*:\s*([\d.]+)\s*,/, px: (value) => value, only: /TextStyle\s*\{/ }
]

/** Text set below 11 px, in px or rems (16 px). */
export function smallTextOffenders(path, { code }) {
  const found = []
  for (const { pattern, px, only } of TEXT_SIZES) {
    for (const match of code.matchAll(new RegExp(pattern.source, 'g'))) {
      if (only && !only.test(code.slice(Math.max(0, match.index - 80), match.index))) continue
      const size = px(Number.parseFloat(match[1]))
      if (size < SMALLEST_TEXT_PX) {
        found.push(`${path}:${lineOf(code, match.index)}: ${match[0].trim()} (${size} px)`)
      }
    }
  }
  return found.sort(byLine)
}

/** The type scale in tokens.rs: every `text::` style is 11 px or more. */
export function tokenTextOffenders(path, source) {
  const scale = /pub mod text \{([\s\S]*?)\n\}/.exec(source)?.[1] ?? ''
  return [...scale.matchAll(/pub const (\w+): TextStyle = TextStyle \{\s*size: ([\d.]+)/g)]
    .filter(([, , size]) => Number.parseFloat(size) < SMALLEST_TEXT_PX)
    .map(([, name, size]) => `${path}: text::${name} is ${size} px`)
}

// ---------------------------------------------------------------- shortcuts

const KEY_GLYPH = /[⌘⇧⌥⌃␣⌫↵⏎↩⌦]/
const CMD_ACCELERATOR = /\b(?:Cmd|Command)\+/
/** The one module that prints key glyphs, per platform, from the keymap. */
export const SHORTCUT_PRINTERS = new Set(['crates/videorc-kit/src/shortcut_keys.rs'])

/** Shortcuts typed by hand: a key glyph or "Cmd+" in a string or char literal. */
export function handTypedShortcutOffenders(path, { strings }) {
  if (SHORTCUT_PRINTERS.has(path)) return []
  return strings
    .filter(({ text }) => KEY_GLYPH.test(text) || CMD_ACCELERATOR.test(text))
    .map(({ line, text }) => `${path}:${line}: ${JSON.stringify(text.trim().slice(0, 60))}`)
}

// ---------------------------------------------------------------- toasts

/** A status tone read off the theme (`theme.warning`, `t.success_foreground`). */
const TONE = /\.(?:destructive|live|success|warning|info)(?:_foreground)?\b(?!\s*\()/g
const ICON = /\bsvg\s*\(|\bIcon\b|\bicon\s*\(|\.path\s*\(/
export const isToastFile = (path) => /(?:^|\/)[\w]*toast[\w]*\.rs$/.test(path)

/**
 * A toast's type colours its icon only (owner call 2026-09-29): in a toast
 * module a tone may paint an `svg()` or icon chain, or sit in a function
 * whose name says icon; anywhere else (the fill, the rim, the shadow, the
 * words) it tints the toast.
 */
export function tintedToastOffenders(path, { code }) {
  if (!isToastFile(path)) return []
  const lines = code.split('\n')
  const tones = [...code.matchAll(TONE)]
  const found = []
  // The functions around each tone, from one pass over the braces.
  const stack = []
  let pending = null
  let cursor = 0
  const fnPattern = /\bfn\s+(\w+)/y
  const fnsAt = new Map()
  for (let index = 0; index <= code.length && fnsAt.size < tones.length; index += 1) {
    while (cursor < tones.length && tones[cursor].index === index) {
      fnsAt.set(index, stack.filter(Boolean))
      cursor += 1
    }
    fnPattern.lastIndex = index
    const fn = fnPattern.exec(code)
    if (fn && !/\w/.test(code[index - 1] ?? '')) pending = fn[1]
    if (code[index] === '{') {
      stack.push(pending)
      pending = null
    } else if (code[index] === '}') {
      stack.pop()
    } else if (code[index] === ';') {
      pending = null
    }
  }
  for (const tone of tones) {
    if ((fnsAt.get(tone.index) ?? []).some((name) => /icon/i.test(name))) continue
    const lineIndex = lineOf(code, tone.index) - 1
    let head = lineIndex
    while (head > 0 && lines[head].trimStart().startsWith('.')) head -= 1
    const lineStart = code.lastIndexOf('\n', tone.index - 1) + 1
    const chain = [...lines.slice(head, lineIndex), code.slice(lineStart, tone.index)].join('\n')
    if (ICON.test(chain)) continue
    found.push(`${path}:${lineIndex + 1}: ${lines[lineIndex].trim().slice(0, 100)}`)
  }
  return found
}

// ---------------------------------------------------------------- the scan

/** The first offender on each line: one colour often matches two patterns. */
function onePerLine(found) {
  const seen = new Set()
  return found.sort(byLine).filter((offender) => {
    const key = offender.split(': ')[0]
    if (seen.has(key)) return false
    seen.add(key)
    return true
  })
}

function byLine(a, b) {
  const [pathA, lineA] = a.split(':')
  const [pathB, lineB] = b.split(':')
  return pathA === pathB ? Number(lineA) - Number(lineB) : pathA.localeCompare(pathB)
}

/** Every `.rs` file under the roots that exist, as repository paths. */
export function gpuiSources(repoRoot, roots = GPUI_ROOTS) {
  const files = []
  const walk = (directory) => {
    for (const entry of readdirSync(directory)) {
      const path = join(directory, entry)
      if (statSync(path).isDirectory()) {
        if (entry !== 'target') walk(path)
      } else if (entry.endsWith('.rs')) {
        files.push(relative(repoRoot, path).split(sep).join('/'))
      }
    }
  }
  for (const root of roots) {
    if (existsSync(join(repoRoot, root))) walk(join(repoRoot, root))
  }
  return files.sort()
}

export const GUARDS = {
  rawColours: rawColourOffenders,
  offTierRadii: offTierRadiusOffenders,
  smallText: smallTextOffenders,
  handTypedShortcuts: handTypedShortcutOffenders,
  tintedToasts: tintedToastOffenders
}

/** Runs every guard over the GPUI sources: `{ guard: offenders[] }`. */
export function scanGpuiSources(repoRoot, roots = GPUI_ROOTS) {
  const result = Object.fromEntries(Object.keys(GUARDS).map((name) => [name, []]))
  for (const path of gpuiSources(repoRoot, roots)) {
    const source = readFileSync(join(repoRoot, path), 'utf8')
    if (path === TOKENS_FILE) {
      result.smallText.push(...tokenTextOffenders(path, source))
      continue
    }
    const lexed = lexRust(source)
    for (const [name, guard] of Object.entries(GUARDS)) result[name].push(...guard(path, lexed))
  }
  return result
}
